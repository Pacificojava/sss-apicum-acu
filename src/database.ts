import 'dotenv/config';
import { Pool } from 'pg';
import bcrypt from 'bcryptjs';

const connectionString = process.env.DATABASE_URL;

if (!connectionString) {
  throw new Error('DATABASE_URL não foi definida. Configure o arquivo .env com a string do Supabase.');
}

const shouldUseSsl =
  Boolean(connectionString) &&
  (
    connectionString.includes('supabase.co') ||
    connectionString.includes('supabase.com') ||
    process.env.NODE_ENV === 'production'
  );

export const db = new Pool({
  connectionString,
  ssl: shouldUseSsl ? { rejectUnauthorized: false } : false,
  connectionTimeoutMillis: 10000,
});

let databaseInitialized = false;

function normalizeQuestionMarks(sql: string, params: unknown[] = []): { text: string; values: unknown[] } {
  let result = '';
  let lastIndex = 0;
  let position = 0;

  for (let i = 0; i < sql.length; i += 1) {
    if (sql.charAt(i) === '?') {
      result += `${sql.slice(lastIndex, i)}$${++position}`;
      lastIndex = i + 1;
    }
  }

  result += sql.slice(lastIndex);

  return {
    text: result,
    values: params,
  };
}

function appendReturningIfNeeded(sql: string): string {
  const trimmed = sql.trim();

  if (/^INSERT\s+/i.test(trimmed) && !/\sRETURNING\b/i.test(trimmed)) {
    return `${trimmed} RETURNING id`;
  }

  return trimmed;
}

export type DatabaseRunResult = {
  lastID: number;
  changes: number;
};

export async function run(sql: string, params: unknown[] = []): Promise<DatabaseRunResult> {
  const normalized = normalizeQuestionMarks(sql, params);
  const result = await db.query(appendReturningIfNeeded(normalized.text), normalized.values);

  return {
    lastID: Number(result.rows[0]?.id ?? 0),
    changes: Number(result.rowCount ?? 0),
  };
}

export async function get<T extends Record<string, unknown>>(sql: string, params: unknown[] = []): Promise<T | null> {
  const normalized = normalizeQuestionMarks(sql, params);
  const result = await db.query<T>(normalized.text, normalized.values);
  return (result.rows[0] as T | null) ?? null;
}

export async function all<T extends Record<string, unknown>>(sql: string, params: unknown[] = []): Promise<T[]> {
  const normalized = normalizeQuestionMarks(sql, params);
  const result = await db.query<T>(normalized.text, normalized.values);
  return (result.rows as T[]) ?? [];
}

export async function initializeDatabase(): Promise<void> {
  if (databaseInitialized) {
    return;
  }

  try {
    await db.query('SELECT 1');

    const schemaStatements = [
      `CREATE TABLE IF NOT EXISTS igrejas (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nome_institucao TEXT NOT NULL,
        chave_contexto TEXT NOT NULL UNIQUE,
        status TEXT NOT NULL DEFAULT 'ativa' CHECK (status IN ('ativa', 'inativa'))
      )`,
      `CREATE TABLE IF NOT EXISTS congregacoes (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        id_igreja INTEGER NOT NULL,
        nome_congregacao TEXT NOT NULL,
        status TEXT NOT NULL DEFAULT 'ativa' CHECK (status IN ('ativa', 'inativa')),
        CONSTRAINT fk_congregacoes_igrejas FOREIGN KEY (id_igreja) REFERENCES igrejas(id) ON DELETE CASCADE
      )`,
      `CREATE TABLE IF NOT EXISTS usuarios (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nome TEXT NOT NULL,
        login TEXT NOT NULL UNIQUE,
        senha_hash TEXT NOT NULL,
        nivel_perfil TEXT NOT NULL CHECK (nivel_perfil IN ('secretaria_geral', 'auxiliar_secretaria')),
        id_igreja INTEGER DEFAULT 1,
        id_congregacao INTEGER NULL,
        CONSTRAINT fk_usuarios_igrejas FOREIGN KEY (id_igreja) REFERENCES igrejas(id) ON DELETE CASCADE
      )`,
      `CREATE TABLE IF NOT EXISTS classes (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nome_classe TEXT NOT NULL UNIQUE
      )`,
      `CREATE TABLE IF NOT EXISTS cargos (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nome TEXT NOT NULL UNIQUE,
        ativo BOOLEAN NOT NULL DEFAULT TRUE
      )`,
      `CREATE TABLE IF NOT EXISTS alunos (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nome TEXT NOT NULL,
        idade INTEGER NOT NULL CHECK (idade >= 0),
        cargo TEXT NOT NULL DEFAULT 'Membro',
        classe_id INTEGER NOT NULL,
        UNIQUE (nome, idade, classe_id),
        CONSTRAINT fk_alunos_classes FOREIGN KEY (classe_id) REFERENCES classes(id) ON DELETE RESTRICT
      )`,
      `CREATE TABLE IF NOT EXISTS frequencias (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        data_aula DATE NOT NULL,
        aluno_id INTEGER NOT NULL,
        classe_id INTEGER NOT NULL,
        presente SMALLINT NOT NULL CHECK (presente IN (0, 1)),
        UNIQUE (data_aula, aluno_id, classe_id),
        CONSTRAINT fk_frequencias_alunos FOREIGN KEY (aluno_id) REFERENCES alunos(id) ON DELETE CASCADE,
        CONSTRAINT fk_frequencias_classes FOREIGN KEY (classe_id) REFERENCES classes(id) ON DELETE RESTRICT
      )`,
      `CREATE TABLE IF NOT EXISTS agendas (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        titulo TEXT NOT NULL,
        descricao TEXT,
        data_evento DATE NOT NULL,
        horario TEXT,
        local TEXT,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )`,
    ];

    for (const statement of schemaStatements) {
      await db.query(statement);
    }

    const totalIgrejas = await get<{ total: number }>('SELECT COUNT(*)::int AS total FROM igrejas');
    if ((totalIgrejas?.total ?? 0) === 0) {
      const seedIgrejas = [
        ['Igreja Sede - Assembleia de Deus', 'JodnaMaia', 'ativa'],
        ['Igreja Exemplo - Apicum-Açu', 'AD-ApicumAcu', 'ativa'],
      ];

      for (const igreja of seedIgrejas) {
        await run('INSERT INTO igrejas (nome_institucao, chave_contexto, status) VALUES (?, ?, ?) ON CONFLICT (chave_contexto) DO NOTHING', igreja);
      }
    }

    const totalUsuarios = await get<{ total: number }>('SELECT COUNT(*)::int AS total FROM usuarios');
    if ((totalUsuarios?.total ?? 0) === 0) {
      const defaultIgreja = await get<{ id: number }>('SELECT id FROM igrejas WHERE chave_contexto = ? LIMIT 1', ['JodnaMaia']);
      const defaultIgrejaId = Number(defaultIgreja?.id ?? 1);
      const seedUsuarios: Array<[string, string, string, string, number, number]> = [
        ['Secretaria Geral', 'secretaria', 'Secretaria@123', 'secretaria_geral', defaultIgrejaId, 1],
        ['Auxiliar da Secretaria', 'auxiliar', 'Auxiliar@123', 'auxiliar_secretaria', defaultIgrejaId, 1],
        ['Jodna Maia Gatinho', 'jodna', 'Jodna@2027', 'secretaria_geral', defaultIgrejaId, 1],
        ['Maria Rita', 'maria', 'Maria@2027', 'auxiliar_secretaria', defaultIgrejaId, 1],
      ];

      for (const [nome, login, senha, nivelPerfil, idIgreja, idCongregacao] of seedUsuarios) {
        const hashed = bcrypt.hashSync(senha, 10);
        await run(
          'INSERT INTO usuarios (nome, login, senha_hash, nivel_perfil, id_igreja, id_congregacao) VALUES (?, ?, ?, ?, ?, ?) ON CONFLICT (login) DO NOTHING',
          [nome, login, hashed, nivelPerfil, idIgreja, idCongregacao],
        );
      }
    }

    const legacySeedPasswords = [
      ['secretaria', 'Secretaria@123'],
      ['auxiliar', 'Auxiliar@123'],
      ['jodna', 'Jodna@2027'],
      ['maria', 'Maria@2027'],
    ] as const;

    for (const [login, senha] of legacySeedPasswords) {
      const hash = bcrypt.hashSync(senha, 10);
      await run('UPDATE usuarios SET senha_hash = ? WHERE login = ?', [hash, login]);
    }

    const totalClasses = await get<{ total: number }>('SELECT COUNT(*)::int AS total FROM classes');
    if ((totalClasses?.total ?? 0) === 0) {
      const seedClasses = ['Infantil', 'Jovens', 'Adultos'];

      for (const nomeClasse of seedClasses) {
        await run('INSERT INTO classes (nome_classe) VALUES (?) ON CONFLICT (nome_classe) DO NOTHING', [nomeClasse]);
      }
    }

    const totalCargos = await get<{ total: number }>('SELECT COUNT(*)::int AS total FROM cargos');
    if ((totalCargos?.total ?? 0) === 0) {
      const seedCargos = [
        'Pastor',
        'Professor(a)',
        'Porteiro',
        'Auxiliar Financeiro(a)',
        'Auxiliar da Sec. de Educação Cristã',
        'Secretário(a) Geral',
        'Tesoureiro(a)',
        'Mídia',
        'Membro',
      ];

      for (const nomeCargo of seedCargos) {
        await run('INSERT INTO cargos (nome, ativo) VALUES (?, TRUE) ON CONFLICT (nome) DO NOTHING', [nomeCargo]);
      }
    }

    const totalAlunos = await get<{ total: number }>('SELECT COUNT(*)::int AS total FROM alunos');
    if ((totalAlunos?.total ?? 0) === 0) {
      const seedAlunos = [
        ['Maria Silva', 12, 1, 'Professor(a)'],
        ['João Pereira', 16, 2, 'Pastor'],
        ['Lucas Costa', 20, 3, 'Auxiliar Financeiro(a)'],
        ['Ana Souza', 27, 3, 'Auxiliar da Sec. de Educação Cristã'],
        ['Pedro Santos', 14, 2, 'Membro'],
      ] as const;

      const defaultClasses = await all<{ id: number }>('SELECT id FROM classes ORDER BY id ASC');

      for (const [nome, idade, classeIdRaw, cargo] of seedAlunos) {
        const classeId = Number(classeIdRaw);
        const actualClasseId = defaultClasses.find((item) => item.id === classeId)?.id ?? defaultClasses[0]?.id;

        if (!actualClasseId) {
          continue;
        }

        await run(
          'INSERT INTO alunos (nome, idade, cargo, classe_id) VALUES (?, ?, ?, ?) ON CONFLICT (nome, idade, classe_id) DO NOTHING',
          [nome, idade, cargo, actualClasseId],
        );
      }
    }

    const totalFrequencias = await get<{ total: number }>('SELECT COUNT(*)::int AS total FROM frequencias');
    if ((totalFrequencias?.total ?? 0) === 0) {
      const seedFrequencias = [
        ['2026-11-01', 1, 1, 1],
        ['2026-11-01', 2, 2, 1],
        ['2026-11-01', 3, 3, 0],
        ['2026-11-02', 1, 1, 1],
        ['2026-11-02', 2, 2, 0],
        ['2026-11-02', 4, 3, 1],
        ['2026-11-03', 5, 2, 1],
      ] as const;

      const alunos = await all<{ id: number; classe_id: number }>('SELECT id, classe_id FROM alunos ORDER BY id ASC');

      for (const [dataAula, alunoIdRaw, classeIdRaw, presente] of seedFrequencias) {
        const alunoId = Number(alunoIdRaw);
        const classeId = Number(classeIdRaw);
        const alunoExiste = alunos.some((aluno) => aluno.id === alunoId);
        const classeExiste = await get<{ id: number }>('SELECT id FROM classes WHERE id = ?', [classeId]);

        if (!alunoExiste || !classeExiste) {
          continue;
        }

        await run(
          'INSERT INTO frequencias (data_aula, aluno_id, classe_id, presente) VALUES (?, ?, ?, ?) ON CONFLICT (data_aula, aluno_id, classe_id) DO NOTHING',
          [dataAula, alunoId, classeId, presente],
        );
      }
    }

    const totalAgendas = await get<{ total: number }>('SELECT COUNT(*)::int AS total FROM agendas');
    if ((totalAgendas?.total ?? 0) === 0) {
      const seedAgendas = [
        ['Reunião de líderes', 'Planejamento semanal com líderes de turma.', '2026-11-08', '08:30', 'Sala 2'],
        ['Aula de Jovens', 'Aula especial para adolescentes e jovens.', '2026-11-10', '19:00', 'Auditório'],
        ['Visita pastoral', 'Visita da equipe pastoral à unidade EBD.', '2026-11-12', '09:00', 'Igreja'],
      ] as const;

      for (const [titulo, descricao, dataEvento, horario, local] of seedAgendas) {
        await run(
          'INSERT INTO agendas (titulo, descricao, data_evento, horario, local) VALUES (?, ?, ?, ?, ?) ON CONFLICT DO NOTHING',
          [titulo, descricao, dataEvento, horario, local],
        );
      }
    }

    databaseInitialized = true;
    console.log('Conexão bem-sucedida ao banco de dados PostgreSQL (Supabase).');
    console.log('Banco de dados SSS inicializado com sucesso.');
  } catch (error) {
    console.error('Erro ao inicializar o banco SSS:', error);
    throw error;
  }
}
